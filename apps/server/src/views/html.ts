export class SafeHtml {
  value: string
  constructor(value: string) {
    this.value = value
  }
  toString() {
    return this.value
  }
}

const escapes: Record<string, string> = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }

export const escape = (value: string) => value.replace(/[&<>"']/g, (ch) => escapes[ch]!)

function render(value: unknown): string {
  if (value === null || value === undefined || value === false) return ''
  if (value instanceof SafeHtml) return value.value
  if (Array.isArray(value)) return value.map(render).join('')
  return escape(String(value))
}

// Tagged template that escapes every interpolated value unless it is already SafeHtml
export function html(strings: TemplateStringsArray, ...values: unknown[]) {
  return new SafeHtml(strings.reduce((out, str, i) => out + str + (i < values.length ? render(values[i]) : ''), ''))
}

export const raw = (value: string) => new SafeHtml(value)

